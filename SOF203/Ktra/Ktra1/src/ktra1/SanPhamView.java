        SanPham ls = sp.get(tbn.getSelectedRow());
        id.setText(String.valueOf(ls.getId()));
        ma.setText(ls.getMa_SP());
        ten.setText(ls.getTen_SP());
        if(ls.getTrang_thai().equals("available")) yes.setSelected(true);
        else {
            no.setSelected(true);
        }
        cbo.setSelectedItem(ls.getDanhMuc());
