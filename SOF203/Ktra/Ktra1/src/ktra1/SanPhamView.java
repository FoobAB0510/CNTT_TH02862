    void defaultLoad() {
        if(db != null) {
            try {
                 ResultSet result = db.prepareStatement(
                         "SELECT ten_danh_muc, san_pham.id, san_pham.ma_san_pham, san_pham.ten_san_pham, san_pham.trang_thai FROM danh_muc INNER JOIN san_pham ON danh_muc.id = san_pham.id_danh_muc"
                 ).executeQuery();
                 DefaultComboBoxModel cb = (DefaultComboBoxModel) cbo.getModel();
                 cb.removeAllElements();
                 
                 while(result.next()) {
                     String danhmuc = result.getString("ten_danh_muc");
                     cb.addElement(danhmuc);
                     sp.add(
                             new SanPham(
                             result.getInt("id"), 
                             result.getString("ma_san_pham"), 
                             result.getString("ten_san_pham"), 
                             result.getString("trang_thai"),
                             danhmuc
                     ));
                 }
                 DefaultTableModel tb = (DefaultTableModel) tbn.getModel();
                 tb.setRowCount(0);
                 for(SanPham ls : sp) {
                     tb.addRow(new Object[] {
                         ls.getId(),
                         ls.getMa_SP(),
                         ls.getTen_SP(),
                         ls.getTrang_thai()
                     });
                 }
            } catch(Exception e) {
                System.out.println("ERROR IN CODE" + e);
            }
        } else {
            System.out.println("NO DATABASE, PLS CONNECT");
        }
    }
