    private void btnGhiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnGhiMouseClicked
        // TODO add your handling code here:
        if (txtTen.getText().isBlank() || cboTheLoai.getSelectedItem().equals("Select") || txtGia.getText().isBlank()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin");
        } else {
            try {
                String ten = txtTen.getText();
                String theLoai = cboTheLoai.getSelectedItem().toString();
                Integer gia = Integer.parseInt(txtGia.getText());

                if (gia < 50) {
                    JOptionPane.showMessageDialog(this, "Giá phải lớn hơn 50");
                } else {
                    int confirm = JOptionPane.showConfirmDialog(this, "Bạn có muốn thêm và ghi file vào không?", "Xác nhận", JOptionPane.YES_NO_OPTION);
                    if (confirm == JOptionPane.YES_OPTION) {
                        Sach sach = new Sach(ten, theLoai, gia);
                        String kq = sv.them(sach);
                        String path = "Sach.txt";
                        ArrayList<Sach> list = sv.getDanhSach();
                        try {
                            FileWriter fileWriter = new FileWriter(path);
                            BufferedWriter bufferedWriter = new BufferedWriter(fileWriter);
                            for (Sach sach1 : list) {
                                bufferedWriter.write(sach1.toString());
                                bufferedWriter.newLine();
                            }
                            bufferedWriter.close();
                        } catch (Exception e) {
                            System.out.println("Có lỗi xảy ra: "+e.getMessage());
                        }
                        loadData(sv.getDanhSach());
                        JOptionPane.showMessageDialog(this, kq);
                    }
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Giá phải là số");
            }
        }
    }//GEN-LAST:event_btnGhiMouseClicked

