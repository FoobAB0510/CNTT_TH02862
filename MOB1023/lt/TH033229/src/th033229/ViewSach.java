    void loadData(ArrayList<Sach> list) {
        DefaultTableModel tableModel = (DefaultTableModel) tblSach.getModel();
        tableModel.setRowCount(0);
        int i = 1;
        for (Sach sach : list) {
            tableModel.addRow(new Object[]{
                i,
                sach.getTen(),
                sach.getTheLoai(),
                sach.getGiaSach()
            });
            i++;
        }
    }

